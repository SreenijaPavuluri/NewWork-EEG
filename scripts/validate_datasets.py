#!/usr/bin/env python3
"""
Validate preprocessed dataset: shape, label balance, channel consistency.

Usage:
  python scripts/validate_datasets.py --dataset physionet --n-subjects 10

Generates results/dataset_report.md with full statistics.
STOP CONDITIONS: exits non-zero if any critical check fails.
"""

import sys
import os
import argparse
import logging
import json
import numpy as np
from pathlib import Path
from collections import Counter

sys.path.insert(0, str(Path(__file__).parent.parent))

from src.utils.logging_utils import setup_logging, get_logger
from src.utils.seed import set_seed

setup_logging()
logger = get_logger(__name__)


def validate_physionet(n_subjects: int = 10, data_dir: str = "data/physionet") -> dict:
    from src.datasets.physionet import load_physionet
    from src.preprocessing.pipeline import PreprocessingConfig

    cfg = PreprocessingConfig(
        target_sfreq=160.0, l_freq=1.0, h_freq=40.0, notch_freq=60.0,
        apply_car=True, normalization="zscore", segment_len_sec=4.0,
    )

    logger.info(f"Loading PhysioNet: {n_subjects} subjects")
    try:
        dataset, meta = load_physionet(
            data_dir=data_dir,
            subjects=list(range(1, n_subjects + 1)),
            preprocess_cfg=cfg,
        )
    except Exception as e:
        logger.error(f"CRITICAL: Dataset loading failed: {e}")
        sys.exit(1)

    # Checks
    checks = {}

    # Shape consistency
    shapes = set(t.shape for t in dataset.trials)
    checks["shape_consistent"] = len(shapes) == 1
    if not checks["shape_consistent"]:
        logger.error(f"CRITICAL: Inconsistent trial shapes: {shapes}")
        sys.exit(1)

    trial_shape = dataset.trials[0].shape
    checks["n_channels"] = trial_shape[0]
    checks["n_timepoints"] = trial_shape[1]
    checks["expected_sfreq"] = 160.0
    checks["actual_timepoints_sec"] = trial_shape[1] / 160.0

    # Label balance
    label_counts = Counter(dataset.labels.tolist())
    checks["class_distribution"] = dict(label_counts)
    max_imbalance = max(label_counts.values()) / max(min(label_counts.values()), 1)
    checks["class_imbalance_ratio"] = round(max_imbalance, 2)

    # Value range check
    all_data = np.stack(dataset.trials[:100])   # check first 100
    checks["mean_zscore_mean"] = float(np.mean(all_data))
    checks["mean_zscore_std"] = float(np.std(all_data))
    checks["value_range"] = [float(all_data.min()), float(all_data.max())]

    # NaN/Inf check
    has_nan = any(np.isnan(t).any() for t in dataset.trials[:50])
    has_inf = any(np.isinf(t).any() for t in dataset.trials[:50])
    checks["has_nan"] = has_nan
    checks["has_inf"] = has_inf

    if has_nan or has_inf:
        logger.error("CRITICAL: NaN or Inf found in preprocessed data. Check preprocessing.")
        sys.exit(1)

    # Subject count
    checks["n_subjects"] = meta["n_subjects"]
    checks["n_trials"] = meta["n_trials"]
    checks["failed_subjects"] = meta.get("failed_subjects", [])

    logger.info(f"Validation passed: {meta['n_trials']} trials, {meta['n_subjects']} subjects")
    logger.info(f"Shape: {trial_shape} | Imbalance ratio: {max_imbalance:.2f}")

    return {
        "name": "PhysioNet EEGMMIDB",
        "checks": checks,
        "meta": meta,
        "status": "PASS",
    }


def write_report(reports: list[dict], save_path: str = "results/dataset_report.md") -> None:
    Path(save_path).parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "# Dataset Report",
        "",
        "> Auto-generated by `scripts/validate_datasets.py`",
        "",
    ]

    for report in reports:
        name = report.get("name", "Unknown")
        status = report.get("status", "UNKNOWN")
        lines += [
            f"## {name}",
            "",
            f"**Status:** {status}",
            "",
        ]

        if "checks" in report:
            c = report["checks"]
            lines += [
                f"| Property | Value |",
                f"|----------|-------|",
                f"| Subjects | {c.get('n_subjects', '?')} |",
                f"| Trials | {c.get('n_trials', '?')} |",
                f"| Channels | {c.get('n_channels', '?')} |",
                f"| Timepoints | {c.get('n_timepoints', '?')} ({c.get('actual_timepoints_sec', '?'):.1f}s) |",
                f"| Sampling Rate | {c.get('expected_sfreq', '?')} Hz |",
                f"| Class Distribution | {c.get('class_distribution', {})} |",
                f"| Class Imbalance Ratio | {c.get('class_imbalance_ratio', '?')} |",
                f"| Value Range | [{c.get('value_range', ['?','?'])[0]:.2f}, {c.get('value_range', ['?','?'])[1]:.2f}] |",
                f"| Has NaN | {c.get('has_nan', '?')} |",
                f"| Has Inf | {c.get('has_inf', '?')} |",
                f"| Failed Subjects | {c.get('failed_subjects', [])} |",
                "",
            ]

        if "meta" in report and "class_distribution" in report["meta"]:
            lines += [
                "### Class Labels",
                "",
                "| Class | Count |",
                "|-------|-------|",
            ]
            for cls, cnt in sorted(report["meta"]["class_distribution"].items()):
                label_names = {0: "Left fist", 1: "Right fist", 2: "Both fists", 3: "Both feet"}
                lines.append(f"| {cls} ({label_names.get(cls, '?')}) | {cnt} |")
            lines.append("")

        lines += ["---", ""]

    lines += [
        "## Dataset Limitations",
        "",
        "- PhysioNet EEGMMIDB: Some subjects have artifacts or poor SNR",
        "- Cross-dataset evaluation limited by different montages and paradigms",
        "- Motor imagery decoding accuracy varies significantly across subjects",
        "  (known problem: some subjects are 'non-responders')",
        "- Preprocessing choices (filter, epoch length) affect comparability",
        "  with published results — we document all choices explicitly",
        "",
        "## Access",
        "",
        "- PhysioNet: https://physionet.org/content/eegmmidb/1.0.0/",
        "  (public domain, no registration required)",
        "- MOABB/BNCI2014_001: https://moabb.neurotechx.com/",
        "  (open-access, CC-BY license)",
    ]

    Path(save_path).write_text("\n".join(lines))
    logger.info(f"Dataset report → {save_path}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dataset", choices=["physionet", "moabb", "both"], default="physionet")
    parser.add_argument("--n-subjects", type=int, default=10)
    parser.add_argument("--data-dir-physionet", default="data/physionet")
    parser.add_argument("--data-dir-moabb", default="data/moabb")
    args = parser.parse_args()

    set_seed(42)
    reports = []

    if args.dataset in ("physionet", "both"):
        r = validate_physionet(args.n_subjects, args.data_dir_physionet)
        reports.append(r)

    write_report(reports)

    # Exit non-zero if any report failed
    for r in reports:
        if r.get("status") != "PASS":
            logger.error(f"Validation FAILED for {r['name']}")
            sys.exit(1)

    logger.info("All validations PASSED")


if __name__ == "__main__":
    main()
